<p>A Lei Geral de Proteção de Dados (LGPD) garante direitos a você, titular dos dados.</p>
<h2>Seus direitos</h2>
<ul>
  <li>Confirmar se tratamos seus dados e acessá-los.</li>
  <li>Corrigir dados incompletos, inexatos ou desatualizados.</li>
  <li>Pedir anonimização, bloqueio ou eliminação de dados desnecessários ou tratados sem base legal.</li>
  <li>Pedir a portabilidade dos dados.</li>
  <li>Saber com quem compartilhamos seus dados.</li>
  <li>Revogar o consentimento a qualquer momento, como o da newsletter e dos cookies.</li>
</ul>
